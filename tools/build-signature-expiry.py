#!/usr/bin/env python3
"""Regenerate expiry SQL from tools/wormholes.json (no database connection)."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = '-- BEGIN GENERATED SIGNATURE EXPIRY POLICY'
END = '-- END GENERATED SIGNATURE EXPIRY POLICY'

def connection_policy(types):
    """Group systems by the attributes used by eligibleWormholeTypes in app.js."""
    app = (ROOT / 'public/js/app.js').read_text()
    generic = json.loads(re.search(r'appData.genericSystemTypes = (\[.*?\]);', app, re.S)[1].replace(',\n\t]', '\n\t]'))
    data = json.loads((ROOT / 'public/js/combine.js').read_text().removeprefix('var appData = '))
    def items(value):
        return value if isinstance(value, list) else [value] if value else []
    named = {v for hole in types.values() for field in ['from', 'leadsTo'] for v in items(hole.get(field))}
    groups = [None]
    systems = {}
    representatives = [None]
    def add(system_id, name, tokens):
        group = {'name': name if name in named else None, 'types': tokens}
        if group not in groups:
            groups.append(group)
            representatives.append(system_id)
        systems[str(system_id)] = groups.index(group)
    for system_id, system in data['systems'].items():
        if system.get('class'):
            tokens = ['Class-' + str(int(c)) for c in items(system['class'])]
        elif int(system.get('factionID') or 0) == 500026:
            tokens = ['Triglavian']
        else:
            security = float(system['security'])
            tokens = ['High-Sec' if security >= .45 else 'Low-Sec' if security > 0 else 'Null-Sec']
        add(int(system_id), system['name'], tokens)
    for index, name in enumerate(generic):
        classes = {'Dangerous': [4, 5], 'Drifter': [14, 15, 16, 17, 18], 'Unknown': [2, 3], 'Unknown (small)': [1, 2, 3, 13]}.get(name)
        add(index, None, ['Class-' + str(c) for c in classes] if classes else [name])
    def matches(hole, field, exclusions, group):
        if group is None:
            return True
        allowed = items(hole.get(field))
        excluded = items(hole.get(exclusions))
        return (not allowed or group['name'] in allowed or bool(set(group['types']) & set(allowed))) and not bool(set(group['types']) & set(excluded))
    maximum = max(round(float(h['life'].split()[0]) * 3600) for h in types.values())
    matrix = []
    for source in groups:
        row = []
        for target in groups:
            eligible = [round(float(h['life'].split()[0]) * 3600) for h in types.values()
                        if (matches(h, 'from', 'notFrom', source) and matches(h, 'leadsTo', 'notLeadsTo', target))
                        or (matches(h, 'from', 'notFrom', target) and matches(h, 'leadsTo', 'notLeadsTo', source))]
            row.append(max(eligible, default=maximum))
        matrix.append(row)
    return {'systems': systems, 'maximum': matrix, 'representatives': representatives}


def sql_rows(rows):
    # Keep generated static lookups compact without creating enormous SQL lines.
    return ',\n'.join('    ' + ', '.join(rows[i:i + 12]) for i in range(0, len(rows), 12))

def policy_sql():
    types = json.loads((ROOT / 'tools/wormholes.json').read_text())
    values = ',\n'.join("    ('%s', %d)" % (key, float(value['life'].split()[0]) * 3600)
                         for key, value in sorted(types.items()))
    policy = connection_policy(types)
    (ROOT / 'tools/signature-connections.json').write_text(json.dumps(policy, separators=(',', ':')) + '\n')
    system_values = sql_rows(['(%s, %s)' % (key, group) for key, group in policy['systems'].items()])
    connection_values = sql_rows(['(%d, %d, %d)' % (a, b, duration)
                                 for a, row in enumerate(policy['maximum']) for b, duration in enumerate(row)])
    global_maximum = policy['maximum'][0][0]
    cap = f"CASE s.type WHEN 'unknown' THEN 86400 WHEN 'wormhole' THEN COALESCE(l.seconds, inferred.seconds, {global_maximum}) ELSE 259200 END"
    origin = "LEAST(s.lifeTime, COALESCE(peer.lifeTime, s.lifeTime), NOW())"
    length = f"IF(s.lifeLength <= 0, {cap}, LEAST(s.lifeLength, {cap}))"
    deadline = f"TIMESTAMPADD(SECOND, {length}, {origin})"
    return f'''{START}
-- Generated by tools/build-signature-expiry.py; edit the JSON, not these values.
CREATE TABLE IF NOT EXISTS signature_lifetime_limits (
    type VARCHAR(4) NOT NULL PRIMARY KEY,
    seconds INT NOT NULL
);
INSERT INTO signature_lifetime_limits (type, seconds) VALUES
{values}
ON DUPLICATE KEY UPDATE seconds = VALUES(seconds);

-- These categories encode the same endpoint eligibility used by the browser.
CREATE TABLE IF NOT EXISTS signature_system_categories (
    systemID INT NOT NULL PRIMARY KEY,
    category SMALLINT NOT NULL
);
INSERT INTO signature_system_categories (systemID, category) VALUES
{system_values}
ON DUPLICATE KEY UPDATE category = VALUES(category);
CREATE TABLE IF NOT EXISTS signature_connection_limits (
    source SMALLINT NOT NULL,
    target SMALLINT NOT NULL,
    seconds INT NOT NULL,
    PRIMARY KEY (source, target)
);
INSERT INTO signature_connection_limits (source, target, seconds) VALUES
{connection_values}
ON DUPLICATE KEY UPDATE seconds = VALUES(seconds);

DROP PROCEDURE IF EXISTS enforceSignatureLifetimes;
DELIMITER ;;
CREATE PROCEDURE enforceSignatureLifetimes()
BEGIN
    DROP TEMPORARY TABLE IF EXISTS signature_expiry_corrections;
    CREATE TEMPORARY TABLE signature_expiry_corrections AS
    SELECT s.id,
           IF(s.lifeLength <= 0 AND COALESCE(w.life, 'stable') <> 'critical',
              {deadline}, LEAST(s.lifeLeft, {deadline})) AS deadline,
           {length} AS duration,
           {origin} AS origin
    FROM signatures s
    LEFT JOIN wormholes w ON (w.initialID = s.id OR w.secondaryID = s.id) AND w.maskID = s.maskID
    LEFT JOIN signature_lifetime_limits l ON l.type = w.type
    LEFT JOIN signatures peer ON peer.id = IF(w.initialID = s.id, w.secondaryID, w.initialID) AND peer.maskID = s.maskID
    LEFT JOIN signature_system_categories sc ON sc.systemID = s.systemID
    LEFT JOIN signature_system_categories tc ON tc.systemID = peer.systemID
    LEFT JOIN signature_connection_limits inferred
      ON inferred.source = COALESCE(sc.category, 0) AND inferred.target = COALESCE(tc.category, 0)
    WHERE s.lifeLength <= 0 OR s.lifeLength > ({cap})
       OR s.lifeTime > {origin}
       OR s.lifeLeft > {deadline};
    UPDATE signatures s
    JOIN signature_expiry_corrections c ON c.id = s.id
    SET s.lifeLeft = IF(s.lifeLength <= 0, c.deadline, LEAST(s.lifeLeft, c.deadline)),
        s.lifeLength = IF(s.lifeLength <= 0, c.duration, LEAST(s.lifeLength, c.duration)),
        s.lifeTime = LEAST(s.lifeTime, c.origin), s.modifiedTime = NOW();
    DROP TEMPORARY TABLE signature_expiry_corrections;
END;;
DELIMITER ;
-- Cap legacy rows without resetting their age or extending an existing deadline.
CALL enforceSignatureLifetimes();
{END}

'''

def render(text):
    if START in text:
        start = text.index(START)
        end = text.index(END, start) + len(END)
        return text[:start] + policy_sql().rstrip() + text[end:]
    at = text.index('DROP EVENT IF EXISTS `signatureClean`;')
    return text[:at] + policy_sql() + text[at:]

if __name__ == '__main__':
    for name in ['tripwire_update.sql', '.docker/mysql/tripwire.sql']:
        path = ROOT / name
        # Preserve the seed schema's CRLF line endings.
        text = render(path.read_bytes().decode())
        for event in ['signatureClean', 'wormholeClean']:
            start = text.index('CREATE EVENT `' + event + '`')
            at = text.index('BEGIN', start) + len('BEGIN')
            at += 2 if text[at:].startswith('\r\n') else 1
            if not text[at:].startswith('    CALL enforceSignatureLifetimes();'):
                text = text[:at] + '    CALL enforceSignatureLifetimes();\n' + text[at:]
        text = text.replace('lifeLeft < NOW() - INTERVAL 0.1 * lifeLength SECOND', 'lifeLeft <= NOW()')
        # New/changed policy lines use LF; retain unrelated seed lines verbatim.
        text = text.replace(END + '\r\n\r\n', END + '\n\n')
        text = text.replace('    CALL enforceSignatureLifetimes();\r\n', '    CALL enforceSignatureLifetimes();\n')
        text = text.replace('      WHERE lifeLeft <= NOW()\r\n', '      WHERE lifeLeft <= NOW()\n')
        path.write_bytes(text.encode())
